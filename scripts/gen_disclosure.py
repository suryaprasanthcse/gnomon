#!/usr/bin/env python3
"""Renders the README's AI-assistance section from .agent/LEDGER.md (rule 11, RUNBOOK_A section 1).

usage: python scripts/gen_disclosure.py [--check]

Rewrites the block between the AI-DISCLOSURE markers in README.md; with --check it only reports whether the README is
current. The ship module's own rows (A17) are left out of the table so that sealing the gate, which appends to the
ledger, never makes the README stale; the section says so.
"""

from __future__ import annotations

import argparse
import re
import sys
from pathlib import Path

ROOT = Path(__file__).resolve().parents[1]
BEGIN, END = "<!-- AI-DISCLOSURE:BEGIN -->", "<!-- AI-DISCLOSURE:END -->"
SHIP = "A17"
COLUMNS = ("utc", "module", "gate", "result", "model", "session", "notes")


def parse(ledger: str) -> list[dict[str, str]]:
    rows = []
    for line in ledger.splitlines():
        cells = [c.strip() for c in line.strip().strip("|").split("|")]
        if line.startswith("|") and len(cells) >= len(COLUMNS) and re.match(r"\d{4}-\d\d-\d\dT", cells[0]):
            rows.append(dict(zip(COLUMNS, cells[: len(COLUMNS) - 1] + ["|".join(cells[len(COLUMNS) - 1:])])))
    return rows


def _modules(rows: list[dict[str, str]]) -> list[str]:
    seen: list[str] = []
    for row in rows:
        for part in re.split(r"\s*\+\s*", re.sub(r"\s*\(.*\)", "", row["module"])):
            if part and part not in seen:
                seen.append(part)
    return sorted(seen)


def render(ledger: str) -> str:
    rows = [r for r in parse(ledger) if SHIP not in r["module"]]
    models = sorted({r["model"] for r in rows})
    lines = [
        "Every module of this repository was implemented by an AI coding assistant (Claude Code, desktop app) working "
        "against tests written first, under the design in `docs/design/master.md`, which was itself drafted with Claude. "
        "The human author, Surya Prasanth R, approved every design decision (`.agent/DECISIONS.md`), answered every "
        "module's explain-back in their own words (`docs/explain/`) and is the sole committer in the git history. "
        "The demos use recorded model responses produced by a deterministic rule-based stand-in (`PolicyLLM`); no live "
        "language model is called by the product.",
        "",
        "| Model | Runs | Modules | First run (UTC) | Last run (UTC) |",
        "|---|---|---|---|---|",
    ]
    for model in models:
        mine = [r for r in rows if r["model"] == model]
        stamps = sorted(r["utc"] for r in mine)
        lines.append(f"| `{model}` | {len(mine)} | {', '.join(_modules(mine))} | {stamps[0]} | {stamps[-1]} |")
    lines += ["", f"{len(rows)} ledger rows, A00 to A16 (the {SHIP} release run is recorded in `.agent/LEDGER.md` when "
              "Gate SHIP is sealed). Generated by `scripts/gen_disclosure.py` from `.agent/LEDGER.md`; do not edit by hand."]
    return "\n".join(lines)


def extract(readme: str) -> str | None:
    found = re.search(re.escape(BEGIN) + r"\n(.*?)\n" + re.escape(END), readme, re.S)
    return found.group(1) if found else None


def splice(readme: str, ledger: str) -> str:
    block = f"{BEGIN}\n{render(ledger)}\n{END}"
    pattern = re.escape(BEGIN) + r".*?" + re.escape(END)
    if not re.search(pattern, readme, re.S):
        raise SystemExit("README.md has no AI-DISCLOSURE markers")
    return re.sub(pattern, lambda _: block, readme, count=1, flags=re.S)


def main(argv: list[str] | None = None) -> int:
    parser = argparse.ArgumentParser(description=__doc__.splitlines()[0])
    parser.add_argument("--check", action="store_true")
    args = parser.parse_args(argv)
    readme_path, ledger_path = ROOT / "README.md", ROOT / ".agent" / "LEDGER.md"
    readme = readme_path.read_text(encoding="utf-8")
    updated = splice(readme, ledger_path.read_text(encoding="utf-8"))
    if args.check:
        print("README AI-assistance section is current" if updated == readme else "README AI-assistance section is stale")
        return 0 if updated == readme else 1
    readme_path.write_text(updated, encoding="utf-8", newline="\n")
    return 0


if __name__ == "__main__":
    sys.exit(main())

"""Conflict matrix (master §7.6): every unordered pair of rules, classified from their parsed footprints.

    overlap(A, B) = W(A) ∩ (R(B) ∪ W(B))  ∪  W(B) ∩ R(A)

A written bare element (a creation or deletion of `X`) also meets every `X.prop` on the other side; a
written property meets only that property. An overlapping element is guarded for a rule when the rule's
guard reads protect it, by the same coverage L1 uses: a property needs a non-identity guard read of its
owner; a creation or deletion needs any guard read of its owner, or an identity check of something created
with it. A projection edge's owner is also its fact type. Classes:

    commutes    no overlap
    guarded     every overlapping element guarded in both rules (Genesis pairs are guarded by PG: it runs
                once, on an empty graph, before any other rule)
    unguarded   anything else; L1 refuses such a rule at registration
"""

from __future__ import annotations

from collections.abc import Iterable, Mapping
from dataclasses import dataclass

from gnomon.footprint.lints import IDENTITY, creation_guarded, owner, prop
from gnomon.footprint.parser import Footprint, extract
from gnomon.kernel.registry import RuleDef


@dataclass(frozen=True)
class Entry:
    a: str
    b: str
    overlap: tuple[str, ...]
    cls: str
    unguarded: tuple[str, ...] = ()


def _touches(w: str, x: str) -> bool:
    return w == x or ("." not in w and x.startswith(w + "."))


def overlap(fa: Footprint, fb: Footprint) -> set[str]:
    out = {w for w in fa.writes if any(_touches(w, x) for x in fb.reads | fb.writes)}
    out |= {w for w in fb.writes if any(_touches(w, x) for x in fa.reads)}
    return out


def guarded(element: str, f: Footprint, owners: set[str]) -> bool:
    if prop(element) is not None:
        return any(owner(r) in owners and prop(r) is not None and prop(r) not in IDENTITY for r in f.guard_reads)
    return any(owner(r) in owners for r in f.guard_reads) or creation_guarded(element, f, f.guard_reads)


def classify(a: RuleDef, b: RuleDef, fa: Footprint, fb: Footprint, projections: Mapping[str, str]) -> Entry:
    names = tuple(sorted((a.name, b.name)))
    shared = overlap(fa, fb)
    if not shared:
        return Entry(*names, (), "commutes")
    if "PG" in (a.prelude, b.prelude):
        return Entry(*names, tuple(sorted(shared)), "guarded")
    bad = []
    for element in sorted(shared):
        owners = {owner(element)} | ({projections[owner(element)]} if owner(element) in projections else set())
        if not (guarded(element, fa, owners) and guarded(element, fb, owners)):
            bad.append(element)
    return Entry(*names, tuple(sorted(shared)), "unguarded" if bad else "guarded", tuple(bad))


def build(rules: Iterable[RuleDef], fact_types: Iterable[Mapping] = ()) -> list[Entry]:
    """Every unordered pair (including each rule with itself), sorted by rule names."""
    projections = {ft["projection"]: ft["rel"] for ft in fact_types if ft.get("projection")}
    ordered = sorted(rules, key=lambda r: r.name)
    prints = {r.name: extract(r.body) for r in ordered}
    entries = []
    for i, a in enumerate(ordered):
        for b in ordered[i:]:
            entries.append(classify(a, b, prints[a.name], prints[b.name], projections))
    return entries


def to_markdown(entries: list[Entry]) -> str:
    counts = {cls: sum(e.cls == cls for e in entries) for cls in ("commutes", "guarded", "unguarded")}
    lines = [
        "# Conflict matrix",
        "",
        "Generated by `gnomon.footprint.matrix` from the parsed footprints of the registered rules (master §7.6).",
        f"{len(entries)} pairs: {counts['commutes']} commute, {counts['guarded']} guarded, "
        f"{counts['unguarded']} unguarded.",
        "",
        "| A | B | Class | Overlap |",
        "|---|---|---|---|",
    ]
    for e in entries:
        lines.append(f"| {e.a} | {e.b} | {e.cls} | {', '.join(e.overlap) or '—'} |")
    return "\n".join(lines) + "\n"
